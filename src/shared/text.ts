export const WORKER_GUIDE = `# 担当の運用指示

あなたは統括から依頼を受けて作業する担当です。役割は join で登録した role のとおりです。

1. 依頼を受けたら：ACK した後、すぐ統括へ [受領 T-番号] を reply_to 付きで返します（作業の概要・見込み・不明点）。ACK だけでは着手が伝わりません。受入条件が不明確なら着手前に [質問] で確認し、勝手に条件を変えません。
2. 作業中：節目ごとに [進捗]、詰まったら [障害]（起きたこと・試したこと・必要な判断）を送ります。他の担当へ直接相談してもよく、範囲に影響する合意は統括にも共有します。
3. 完了したら：[完了 T-番号] を元の依頼の message_id を reply_to にして送ります。成果物（パス・差分の要約）、受入条件ごとの確認結果と確認方法、未解決事項、レビューしてほしい点を含めます。差し戻しが来たら同じ T-番号で対応し、再度 [完了] を送ります。
4. 区切りごとに channel_receive で新しい指示がないか確認します。`;

export function guideFor(duty: 'coordinator' | 'worker'): string {
  return duty === 'coordinator' ? COORDINATOR_GUIDE : WORKER_GUIDE;
}

export function instructionsFor(duty: 'coordinator' | 'worker'): string {
  return `${COMMON_GUIDE}\n\n${guideFor(duty)}`;
}
